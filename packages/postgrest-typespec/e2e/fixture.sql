-- Schema for the end-to-end tests. It exercises the generic API surface,
-- not any Supabase schema.

create role authenticator noinherit login password 'authenticator';
create role anon nologin;
create role app_user nologin;
grant anon, app_user to authenticator;

create schema api;
create schema tenant2;

create table api.directors (
  id int primary key,
  name text not null
);

create table api.films (
  id int primary key,
  title text not null,
  year int,
  director_id int references api.directors,
  tags text[],
  meta jsonb
);

create table api.items (
  id int generated by default as identity primary key,
  name text unique not null,
  qty int default 10
);

create table api.secrets (
  id int primary key,
  value text
);

-- No role has privileges on this table.
create table api.audit (
  id int primary key
);

create view api.film_titles as select id, title from api.films;

insert into api.directors values (1, 'Lumière'), (2, 'Tarantino');
insert into api.films values
  (1, 'Workers Leaving The Lumière Factory', 1895, 1, '{short,silent}', '{"runtime": 46}'),
  (2, 'Reservoir Dogs', 1992, 2, '{crime}', '{"runtime": 99}'),
  (3, 'Pulp Fiction', 1994, 2, '{crime,cult}', '{"runtime": 154}');
insert into api.secrets values (1, 'hidden');

create function api.add(a int, b int) returns int
language sql immutable as $$ select a + b $$;

create function api.films_since(since int) returns setof api.films
language sql stable as $$ select * from api.films where year >= since $$;

create function api.touch_items() returns void
language sql volatile as $$ update api.items set qty = qty $$;

create function api.echo_json(json) returns json
language sql immutable as $$ select $1 $$;

create function api.echo_text(text) returns text
language sql immutable as $$ select $1 $$;

create function api.echo_xml(xml) returns xml
language sql immutable as $$ select $1 $$;

create function api.byte_length(bytea) returns int
language sql immutable as $$ select length($1) $$;

create function api.sum_all(variadic v int[]) returns int
language sql immutable as $$ select sum(x)::int from unnest(v) x $$;

create function api.pay() returns void
language plpgsql as $$
begin
  raise sqlstate 'PT402' using message = 'Payment Required', detail = 'Quota exceeded';
end $$;

create table tenant2.items (
  id int primary key,
  name text
);
insert into tenant2.items values (1, 'tenant2 item');

grant usage on schema api, tenant2 to anon, app_user;
grant select on api.directors, api.films, api.film_titles, tenant2.items to anon, app_user;
grant all on api.items to anon, app_user;
grant select on api.secrets to app_user;
grant execute on all functions in schema api to anon, app_user;
